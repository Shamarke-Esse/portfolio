Vector = a small collection of numbers. 

Any object that contains data is called a data structure.

Numberic vectors are the simplest type of data structure in R

A single number is considered a vector of length one

To create a vector: c(n1,n2,n3 etc). The C stands for concatenate.
example a vector with number 1, 5 , 8.9 = c(1,5,8.9)

To store as results create vector variable 

P <- c(1,5,8.9)

to view the contents of the vector just created type the variable name



typing P shows the results 1.00 5.00 8.90

You can combine vectors to make a new vector. 

Example: create a vector that contains P,555 and P

c(P, 555, P)

Numberic Vectors can used in arithmetic expressions

'+', '-', '/', '^' (means squared e.g x^2 = xsquared), sqrt() (square root of value or variable e.g sqrt(x). 

